"""Rendering one document model to Markdown and to offline HTML.

A document is a dict: {"title", "subtitle", "simulated", "sections": [...]}.
Each section is {"h": heading, "blocks": [...]} and a block is one of:
  {"p": text} {"note": text} {"ul": [text]} {"table": {"head": [...], "rows": [[cell]]}}
  {"pair": {"before": evidence, "after": evidence, "caption": text}}
A table cell is text, or {"badges": [label, ...]}, or {"code": text}.
"""

from __future__ import annotations

import html
import re
from pathlib import Path
from string import Template

from . import __version__
from .store import REPO_ROOT, write_text

SIMULATED_BANNER = "SIMULATED: this report was produced with a fake phone (tests/fake_adb.py). It is not a real device result."
EXPERIMENTAL = "Experimental. Not yet tested on a real device. Use at your own risk and back up your data first."


def _slug(label):
    return "b-" + re.sub(r"[^a-z0-9]+", "-", label.lower()).strip("-")


def _cell_md(cell):
    if isinstance(cell, dict):
        if "badges" in cell:
            return ", ".join("`%s`" % b for b in cell["badges"]) or "-"
        if "code" in cell:
            return "`%s`" % cell["code"]
    text = str(cell if cell is not None else "")
    return text.replace("|", "\\|").replace("\n", " ") or "-"


def _cell_html(cell):
    if isinstance(cell, dict):
        if "badges" in cell:
            return "".join('<span class="badge %s">%s</span>' % (_slug(b), html.escape(b)) for b in cell["badges"]) or "-"
        if "code" in cell:
            return "<code>%s</code>" % html.escape(cell["code"])
    return html.escape(str(cell if cell is not None else "")) or "-"


def to_markdown(doc):
    out = ["# " + doc["title"], ""]
    if doc.get("subtitle"):
        out += ["_" + doc["subtitle"] + "_", ""]
    if doc.get("simulated"):
        out += ["> **" + SIMULATED_BANNER + "**", ""]
    out += ["> " + EXPERIMENTAL, ""]
    for sec in doc["sections"]:
        out += ["## " + sec["h"], ""]
        for b in sec["blocks"]:
            if "p" in b:
                out += [b["p"], ""]
            elif "note" in b:
                out += ["> " + b["note"], ""]
            elif "ul" in b:
                out += ["- " + str(i) for i in b["ul"]] + [""]
            elif "table" in b:
                t = b["table"]
                if not t["rows"]:
                    out += ["_Nothing to show._", ""]
                    continue
                out.append("| " + " | ".join(t["head"]) + " |")
                out.append("|" + "---|" * len(t["head"]))
                for row in t["rows"]:
                    out.append("| " + " | ".join(_cell_md(c) for c in row) + " |")
                out.append("")
            elif "pair" in b:
                pr = b["pair"]
                out.append("**%s**" % pr["caption"])
                out.append("")
                for side in ("before", "after"):
                    ev = pr.get(side) or {}
                    img = ev.get("image")
                    out.append("- %s: %s%s" % (side.capitalize(), ev.get("summary", "not checked"),
                                                (" (image: `%s`)" % img) if img else ""))
                out.append("")
    out += ["---", "", "Generated by AdReceipts %s. Files stay on this computer." % __version__, ""]
    return "\n".join(out)


def _pair_html(pr):
    figs = []
    for side in ("before", "after"):
        ev = pr.get(side) or {}
        img = ev.get("image")
        if img:
            body = '<img src="%s" alt="%s screen of %s">' % (html.escape(img), side, html.escape(pr["caption"]))
        else:
            body = '<div class="placeholder">No image (%s)</div>' % html.escape(ev.get("summary", "not checked"))
        figs.append("<figure>%s<figcaption><strong>%s</strong>: %s</figcaption></figure>"
                    % (body, side.capitalize(), html.escape(ev.get("summary", "not checked"))))
    return '<div class="card"><p><strong>%s</strong></p><div class="pairs">%s</div></div>' % (
        html.escape(pr["caption"]), "".join(figs))


def to_html(doc, template="report.html"):
    parts = []
    for sec in doc["sections"]:
        parts.append("<h2>%s</h2>" % html.escape(sec["h"]))
        for b in sec["blocks"]:
            if "p" in b:
                parts.append("<p>%s</p>" % html.escape(b["p"]))
            elif "note" in b:
                parts.append('<div class="note">%s</div>' % html.escape(b["note"]))
            elif "ul" in b:
                parts.append("<ul>%s</ul>" % "".join("<li>%s</li>" % html.escape(str(i)) for i in b["ul"]))
            elif "table" in b:
                t = b["table"]
                if not t["rows"]:
                    parts.append("<p><em>Nothing to show.</em></p>")
                    continue
                head = "".join("<th>%s</th>" % html.escape(h) for h in t["head"])
                rows = "".join("<tr>%s</tr>" % "".join("<td>%s</td>" % _cell_html(c) for c in r) for r in t["rows"])
                parts.append('<div class="table-wrap"><table><thead><tr>%s</tr></thead><tbody>%s</tbody></table></div>' % (head, rows))
            elif "pair" in b:
                parts.append(_pair_html(b["pair"]))
    banner = ""
    if doc.get("simulated"):
        banner += '<div class="banner">%s</div>' % html.escape(SIMULATED_BANNER)
    banner += '<div class="note">%s</div>' % html.escape(EXPERIMENTAL)
    tpl = Template((REPO_ROOT / "templates" / template).read_text(encoding="utf-8"))
    return tpl.substitute(
        title=html.escape(doc["title"]),
        subtitle=html.escape(doc.get("subtitle", "")),
        banner=banner,
        content="\n".join(parts),
        footer=html.escape("Generated by AdReceipts %s. This page works offline and loads nothing from the internet. Files stay on this computer." % __version__),
    )


def write(doc, folder, name, template="report.html"):
    folder = Path(folder)
    write_text(folder / (name + ".md"), to_markdown(doc))
    write_text(folder / (name + ".html"), to_html(doc, template))
    return folder / (name + ".html")


def device_line(dev):
    bits = [dev.get("brand", ""), dev.get("model", "")]
    line = " ".join(b for b in bits if b).strip() or "Unknown phone"
    if dev.get("android"):
        line += ", Android %s" % dev["android"]
    if dev.get("system"):
        line += ", system %s" % dev["system"]
    return line


